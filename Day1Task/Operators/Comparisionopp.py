val1=int(input("Enter the first value:"))
val2=int(input("Enter the second value:"))
equ=(val1==val2)
print("Using Equals operator between two numbers:",equ)
nequ=(val1!=val2)
print("Using Not Equals operator between 2 numbers:",nequ)
great=(val2>val1)
print("Using Greaterthan operator between 2 numbers:",great)
greatequ=(val1>=val2)
print("Using Greaterthan Equals to operator between 2 numbers:",greatequ)
less=(val2<val1)
print("Using lessthan operator between 2 numbers:",less)
lessequ=(val1<=val2)
print("Using Lessthan Equals to operator between 2 numbers:",lessequ)
